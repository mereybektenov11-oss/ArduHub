// Generates src/renderer/learning/neon-on-primary.generated.css.
//
// The site's lesson CSS puts dark text (--ink-900 / --text-dark) on amber
// buttons. The app's night theme swaps dark and light tokens, which would
// leave light text on the cyan primary colour. This script finds every rule
// with an amber background in the site's lesson CSS and pins its text to the
// dark "on primary" colour. Variants of those components that switch back to
// a neutral background (e.g. .cab-btn-secondary) get the normal light text.
// Re-run after changing those site styles:
//   node apps/desktop/scripts/gen-neon-overrides.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../../", import.meta.url));
const files = [
  "src/app/globals.css",
  "src/app/app/cabinet.css",
  "src/app/app/learning.css",
  "src/app/app/dashboard.css",
  "src/app/app/lesson-flow.css",
  "src/app/app/kids-pages.css",
  "src/app/app/kids-mentor.css",
  "src/app/app/kids-workspace.css",
  "src/app/app/kids-home.css",
  "src/app/app/event-feedback.css",
];
const amber =
  /background(-color)?\s*:[^;]*var\(--(amber-500|amber-600|glass-amber[\w-]*)\)/;
const neutral =
  /background(-color)?\s*:[^;]*(var\(--(cream-50|cream-100|white|cab-border|line-dark|surface-[\w-]+|glass-light)\)|transparent|none)/;
const classesOf = (selector) => selector.match(/\.[\w-]+/g) ?? [];

const rules = [];
for (const file of files) {
  const css = readFileSync(root + file, "utf8").replace(
    /\/\*[\s\S]*?\*\//g,
    "",
  );
  // Innermost rules only: a "{" whose block has no nested "{".
  for (const m of css.matchAll(/([^{};]+)\{([^{}]*)\}/g)) {
    const selector = m[1].trim();
    if (
      !selector ||
      selector.startsWith("@") ||
      /^(from|to|\d+%)/.test(selector)
    )
      continue;
    rules.push({
      selectors: selector.split(",").map((x) => x.trim()),
      body: m[2],
    });
  }
}

const onPrimary = new Set();
for (const r of rules)
  if (amber.test(r.body)) r.selectors.forEach((x) => onPrimary.add(x));
const amberClasses = new Set([...onPrimary].flatMap(classesOf));
const restore = new Set();
for (const r of rules)
  if (!amber.test(r.body) && neutral.test(r.body))
    for (const x of r.selectors)
      if (
        !onPrimary.has(x) &&
        classesOf(x).some((c) =>
          [...amberClasses].some((a) => c === a || c.startsWith(a + "-")),
        )
      )
        restore.add(x);

const scope = (set) =>
  [...set]
    .sort()
    .map((x) => `:root:has(.learning-area) ${x}`)
    .join(",\n");
// Same specificity, later wins: neutral variants come after the amber rules.
const out = `/* Generated by apps/desktop/scripts/gen-neon-overrides.mjs — do not edit. */
${scope(onPrimary)} {
  color: var(--neon-on-primary);
}
${scope(restore)} {
  color: var(--text-dark);
}
`;
writeFileSync(
  fileURLToPath(
    new URL(
      "../src/renderer/learning/neon-on-primary.generated.css",
      import.meta.url,
    ),
  ),
  out,
);
console.log(`${onPrimary.size} on-primary, ${restore.size} restored`);
