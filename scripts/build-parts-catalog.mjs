import { chromium } from "@playwright/test";
import { readFile, writeFile } from "node:fs/promises";
const browser = await chromium.launch({ channel: "chrome" });
try {
  const page = await browser.newPage();
  await page.evaluate(() => {
    window.registeredParts = [];
    const define = customElements.define.bind(customElements);
    customElements.define = (name, constructor, options) => {
      window.registeredParts.push(name);
      return define(name, constructor, options);
    };
  });
  await page.addScriptTag({
    content: await readFile(
      "node_modules/@wokwi/elements/dist/wokwi-elements.bundle.js",
      "utf8",
    ),
  });
  const data = await page.evaluate(async () => {
    const result = {};
    for (const tag of window.registeredParts.filter((t) =>
      t.startsWith("wokwi-"),
    )) {
      const element = document.createElement(tag);
      document.body.append(element);
      await element.updateComplete;
      const svgs = [...(element.shadowRoot?.querySelectorAll("svg") ?? [])];
      const box =
        svgs
          .map((s) => s.getBoundingClientRect())
          .sort((a, b) => b.width * b.height - a.width * a.height)[0] ??
        element.getBoundingClientRect();
      result[tag.slice(6)] = {
        tag,
        module: tag.slice(6),
        width: Math.max(20, box.width),
        height: Math.max(20, box.height),
        pins: (element.pinInfo ?? []).map(({ name, x, y }) => ({ name, x, y })),
        attrs: Object.fromEntries(
          ["value", "color", "common", "frequency", "pins"]
            .map((name) => [name, element[name]])
            .filter(
              ([, value]) =>
                (typeof value === "string" && value.length <= 40) ||
                (typeof value === "number" && Number.isFinite(value)),
            ),
        ),
      };
      element.remove();
    }
    return result;
  });
  await writeFile(
    "src/domain/parts/catalog.generated.json",
    JSON.stringify(data, null, 2) + "\n",
  );
  const aliases = {
    "arduino-uno": "uno",
    "rgb-led": "rgb",
    pushbutton: "button",
    "slide-switch": "switch",
    potentiometer: "pot",
    "photoresistor-sensor": "ldr",
    lcd1602: "lcd",
    "7segment": "segment",
    "hc-sr04": "ultrasonic",
    dht22: "dht",
  };
  const keys = Object.keys(data);
  await writeFile(
    "src/domain/parts/loaders.generated.ts",
    "// Generated by pnpm parts:build.\nexport const partLoaders: Record<string, () => Promise<unknown>> = {\n" +
      keys
        .map(
          (key) =>
            `  ${JSON.stringify(aliases[key] ?? key)}: () => import("@wokwi/elements/dist/esm/${key}-element"),`,
        )
        .join("\n") +
      "\n};\n",
  );
  console.log(
    `Из установленного пакета извлечено ${keys.length} деталей. Макетная плата: ${keys.includes("breadboard") ? "есть" : "в пакете отсутствует"}.`,
  );
} finally {
  await browser.close();
}
